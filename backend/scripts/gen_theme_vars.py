"""Write mathion/theme_vars.py from frontend/src/styles/theme-default.css (Branding D8).

The app's image holds the built frontend, not theme-default.css, so the server
reads the overridable colours from this generated module. A colour is a
variable whose default is a literal colour or var() of another colour. Run
from backend/ after changing theme-default.css:
    .venv/bin/python scripts/gen_theme_vars.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT.parent / "frontend" / "src" / "styles" / "theme-default.css"

# Each section comment's first words -> the download's family heading (D9).
HEADINGS = {
    "surfaces": "Page and surfaces",
    "text": "Text",
    "lines": "Borders",
    "accent": "Primary",
    "gold": "Gold",
    "semantic": "Status colours",
    "toast": "Toast",
    "destructive button": "Danger button",
    "confirm buttons": "Confirm buttons",
    "the danger panel": "Danger panel",
    "avatars": "Avatars",
    "progress heatmap": "Progress heat map",
    "submission status": "Submission status",
    "version lifecycle badges": "Version badges",
}

_LITERAL = re.compile(r"#[0-9a-fA-F]{3,8}|rgba?\([^()]*\)|hsla?\([^()]*\)")
_VAR = re.compile(r"var\(\s*(--[\w-]+)\s*\)")
# A section comment, a declaration, or any other comment, in file order.
# A section's name ends at ":", "(", ",", the closing "---" or the line's end.
_TOKEN = re.compile(r"/\*\s*---\s*([^:(,\n]*?)\s*(?:[:(,\n]|---)(?:.|\n)*?\*/|/\*(?:.|\n)*?\*/|(--[\w-]+)\s*:\s*([^;]+);")


def read() -> tuple[list[tuple[str, str, str]], list[str]]:
    """The colours as (name, default, section) and the other variables' names."""
    colours: dict[str, tuple[str, str]] = {}
    others: list[str] = []
    section = ""
    for m in _TOKEN.finditer(CSS.read_text()):
        if m.group(1) is not None:
            section = m.group(1).strip()
        elif m.group(2) is not None:
            name, value = m.group(2), m.group(3).strip()
            ref = _VAR.fullmatch(value)
            if _LITERAL.fullmatch(value) or (ref and ref.group(1) in colours):
                colours[name] = (value, section)
            else:
                others.append(name)
    return [(n, v, s) for n, (v, s) in colours.items()], others


def main() -> int:
    colours, others = read()
    missing = sorted({s for _, _, s in colours if s not in HEADINGS})
    if missing:
        print(f"gen_theme_vars: no heading for the section(s) {', '.join(repr(s) for s in missing)}; "
              "add them to HEADINGS", file=sys.stderr)
        return 1
    lines = [
        '"""The overridable theme colours (Branding D8). Generated by scripts/gen_theme_vars.py',
        'from frontend/src/styles/theme-default.css; don\'t edit by hand."""',
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass(frozen=True)",
        "class ThemeVar:",
        "    name: str",
        "    default: str",
        "    heading: str",
        "",
        "",
        "THEME_VARS: tuple[ThemeVar, ...] = (",
    ]
    lines += [f"    ThemeVar({n!r}, {v!r}, {HEADINGS[s]!r})," for n, v, s in colours]
    lines += [
        ")",
        "",
        "BY_NAME: dict[str, ThemeVar] = {v.name: v for v in THEME_VARS}",
        "",
        "# The theme's other variables (sizes, spacing, fonts, shadows): never changed by a school.",
        "NON_COLOUR_NAMES: frozenset[str] = frozenset({",
    ]
    lines += [f"    {n!r}," for n in others]
    lines.append("})")
    (ROOT / "mathion" / "theme_vars.py").write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
